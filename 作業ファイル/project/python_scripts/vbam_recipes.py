def _parse_sheet_recipes(text):
    recipes, name, body = {}, None, []
    for line in text.splitlines():
        if line.startswith('■'):
            if name:
                recipes[name] = "\n".join(body).strip()
            name, body = line[1:].strip(), []
        else:
            body.append(line)
    if name:
        recipes[name] = "\n".join(body).strip()
    return recipes


SHEET_RECIPES = _parse_sheet_recipes(_SHEET_RECIPES_TEXT)


def recipe_when(name):
    """手順書の「いつ:」の 1 行（一覧用）。"""
    body = SHEET_RECIPES.get(name, '')
    return next((l[len('いつ: '):] for l in body.splitlines() if l.startswith('いつ: ')), '')


def compose_recipe_request(name, supplement=''):
    """手順書＋補足 → 依頼文。補足は承認の言葉（「置き換えてよい」等）や番地・仕様を渡す口。"""
    if name not in SHEET_RECIPES:
        raise ValueError(f"無い手順書: {name}（ある手順書: " + "、".join(SHEET_RECIPES) + "）")
    sup = (supplement or '').strip()
    return f"手順書「{name}」\n" + SHEET_RECIPES[name] + "\n補足: " + (sup if sup else "なし")


