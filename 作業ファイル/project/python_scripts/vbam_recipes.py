def _put(ws, row, col, rows, text_cols=()):
    """(row, col) を左上に 2 次元リストを書く。text_cols は 0 始まりの列番号＝先に '@' にする（先頭ゼロ・文字の数字）。"""
    m = max(len(r) for r in rows)
    grid = [list(r) + [None] * (m - len(r)) for r in rows]
    rng = ws.Range(ws.Cells(row, col), ws.Cells(row + len(rows) - 1, col + m - 1))
    for j in text_cols:
        ws.Range(ws.Cells(row, col + j), ws.Cells(row + len(rows) - 1, col + j)).NumberFormat = "@"
    rng.Value = grid
    return rng


def _text_cell(ws, addr, value):
    ws.Range(addr).NumberFormat = "@"
    ws.Range(addr).Value = value


def _norm(v):
    """セルの値を比べやすい文字にする（12000.0 → '12000'、日付 → 'yyyy/m/d'、前後の空白は残す）。"""
    if v is None:
        return ''
    if isinstance(v, bool):
        return 'TRUE' if v else 'FALSE'
    if isinstance(v, float):
        return str(int(v)) if v.is_integer() else str(v)
    if isinstance(v, int):
        return str(v)
    if hasattr(v, 'year') and hasattr(v, 'month'):
        return f"{v.year}/{v.month}/{v.day}"
    return str(v)


def _is_date(v):
    return hasattr(v, 'year') and hasattr(v, 'month') and not isinstance(v, str)


def _is_number(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _grid(ws, addr):
    """範囲の値を 2 次元リストで（1 セルでも [[v]]）。"""
    v = ws.Range(addr).Value
    if not isinstance(v, tuple):
        return [[v]]
    return [list(r) if isinstance(r, tuple) else [r] for r in v]


def _row_values(ws, row, c0, c1):
    return [ws.Cells(row, c).Value for c in range(c0, c1 + 1)]


def _unchanged(ws, addr, planted):
    """植えた値と今の値の食い違い（番地の一覧）。"""
    bad = []
    now = _grid(ws, addr)
    r0 = ws.Range(addr).Row
    c0 = ws.Range(addr).Column
    for i, row in enumerate(planted):
        for j, want in enumerate(row):
            got = now[i][j] if i < len(now) and j < len(now[i]) else None
            if _norm(got) != _norm(want):
                bad.append(f"{_col_letter(c0 + j)}{r0 + i}={_norm(got)!r}")
    return bad


def _find_in_rows(ws, rows, c0, c1, want, pred=None):
    """各行 r について c0..c1 のどこかに want（または pred が真の値）があるか。無い行の一覧を返す。"""
    missing = []
    for r in rows:
        vals = _row_values(ws, r, c0, c1)
        ok = any((pred(v) if pred else _norm(v) == _norm(want[r] if isinstance(want, dict) else want))
                 for v in vals)
        if not ok:
            missing.append(r)
    return missing


def _formula_cells(ws, addr, contains=None):
    out = []
    rng = ws.Range(addr)
    r0, c0 = rng.Row, rng.Column
    fr = rng.Formula
    if not isinstance(fr, tuple):
        fr = ((fr,),)
    for i, row in enumerate(fr):
        for j, f in enumerate(row):
            if isinstance(f, str) and f.startswith('=') and (contains is None or contains.lower() in f.lower()):
                out.append(f"{_col_letter(c0 + j)}{r0 + i}")
    return out


def _numbers_in(ws, addr):
    vals = []
    for row in _grid(ws, addr):
        for v in row:
            if _is_number(v):
                vals.append(round(float(v), 2))
    return vals


def _report_has(r, *words):
    rep = (r.get('report') or '')
    return [w for w in words if w not in rep]


def _touched(ws, addr):
    """範囲に何か書かれているか（報告だけの手順書で「書いていない」を確かめる用）。"""
    return [f"{_col_letter(ws.Range(addr).Column + j)}{ws.Range(addr).Row + i}"
            for i, row in enumerate(_grid(ws, addr)) for j, v in enumerate(row) if v not in (None, '')]


