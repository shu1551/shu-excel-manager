def recipe_case_label(case):
    """実射の結果に出す名前（統合した手順書は variant を添える）。"""
    return f"手順書「{case['name']}」" + (f"（{case['variant']}）" if case.get('variant') else "")

_RECIPE_MAX_TURNS = 6


def _fire_recipe_cases(xl, cases, ai, model, states=None, show_image=True, grade_ai=None, grade_model=None):
    """手順書の自動実射: まっさらなブックに練習台を組み、手順書を撃ち、現物で答え合わせ（保存せず閉じる）。
    show_image／grade_ai／grade_model は run_agent にそのまま渡す（--no-image・--grade-ai の効果を実射で測る・2026-09-06 夜）。"""
    from vbam_agent import (run_agent, _snapshot_book, _inv_violations,   # 循環 import を避けて遅延
                            _gate_line, _gate_grade)
    from vbam_fire import _apply_state                                  # 練習台の状態は 2026-09-11 から vbam_fire
    wb = xl.Workbooks.Add()
    print(f"実射用のブック（手順書）: {wb.Name}（終わったら保存せず閉じます）")
    results = []
    try:
        for case in cases:
            sheet = f"実射{case['no']}"
            st, label = (states or {}).get(case['name'], ""), ""
            info = {}
            print(f"\n===== 実射: {recipe_case_label(case)}→ シート {sheet} =====")
            ctx = {}
            t0 = time.time()
            try:
                ws = wb.Worksheets.Add(After=wb.Worksheets(wb.Worksheets.Count))
                ws.Name = sheet
                ctx = case['build'](xl, wb, ws) or {}
                st_note = _apply_state(ws, st)                 # 練習台の状態（2026-09-05）
                # 状態を当てた**後**の姿を答え合わせの基準にする（2026-09-07 未明）。
                # 組んだ直後の数で見ていたので、状態が条件付き書式を 1 本足すだけで
                # 「消してよいと言っていないのに消えた」と誤って不合格にしていた
                try:
                    ctx.setdefault('_shapes0', int(ws.Shapes.Count))
                    ctx.setdefault('_cf0', int(ws.Cells.FormatConditions.Count))
                except Exception:
                    pass
                label = f"[{st}] " if st_note else ""          # 当たった状態だけ名乗る
                print(f"練習台の状態: {st_note if st_note else f'なし（{st} は当てられない練習台）'}")
                ws.Activate()
                sup = case.get('supplement') or ''
                if callable(sup):
                    sup = sup(ctx)
                req = compose_recipe_request(case['name'], sup)
                snap = _snapshot_book(wb)                  # 撃つ前の姿（頼んでいない変化を見るため・2026-09-05）
                r = run_agent(req, sheet, wb, ai, model, backup=False,
                              max_turns=case.get('max_turns', _RECIPE_MAX_TURNS),
                              verify=True, show_image=show_image, grade_ai=grade_ai, grade_model=grade_model)
                info = {'turns': r.get('turns'), 'gates': dict(r.get('gates') or {}),
                        'report': r.get('report'), 'asks': r.get('asks'), 'dropped': r.get('dropped')}
                ok, note = case['check'](ws, ctx, r)
                # 合否は現物（セル・図形・印刷設定・出力ファイル）で決める。AI の done は往復上限で言えないことがある
                ok = ok and (r['done'] or r['verify'])
                if not r['done']:
                    note += "（AI は done を言っていない）"
                inv = _inv_violations(wb, snap, sheet,
                                      tuple(set(case.get('inv_skip', ())) | set(r.get('inv_skip') or ())))   # 本番と同じ物差し
                if inv:
                    ok = False
                    note += "／頼んでいない変化: " + "／".join(inv[:3])
                note += f"  {time.time() - t0:.1f}秒・往復 {r['turns']}"
                print(f"答え合わせ: {note}")
                print(_gate_line(info.get('gates')) + f"　＝ {_gate_grade(ok, info.get('gates'))}")
            except Exception as ex:
                print(f"エラー: {ex}")
                ok, note = False, str(ex)
            finally:
                cl = ctx.get('cleanup') if isinstance(ctx, dict) else None
                if cl:
                    try:
                        cl()
                    except Exception:
                        pass
            results.append((recipe_case_label(case), ok, label + note, info))
    finally:
        try:
            wb.Close(SaveChanges=False)
        except Exception as ex:
            print(f"⚠ 実射用のブックを閉じられませんでした: {ex}")
    return results


